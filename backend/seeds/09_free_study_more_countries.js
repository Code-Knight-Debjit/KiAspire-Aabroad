const AUSTRIA = `Austria's public universities are close to Germany's model, with one
distinction worth knowing upfront: EU/EEA students pay little to nothing,
while non-EU students (including Indian applicants) pay a modest fixed
tuition fee rather than the market-rate tuition charged in the US, UK, or
Australia.

## What "low-cost" actually means

Non-EU students at Austrian public universities typically pay a tuition
fee in the range of a few hundred euros per semester, plus a small student
union (ÖH) contribution — a fraction of tuition at comparable Western
universities, and stable rather than rising year over year the way
private-market tuition often does.

## What you'll still need to budget for

- **Proof of financial resources:** required for your student visa,
  broadly similar in spirit to Germany's blocked-account requirement.
- **Health insurance:** mandatory for enrollment and visa approval.
- **Living costs:** Vienna, Graz, and Innsbruck are moderately priced by
  Western European standards, but this is real ongoing spending.

## Eligibility basics

- Recognized academic transcripts, with some programs requiring a
  credential recognition step before admission.
- English-taught master's programs are increasingly common, especially in
  technical and business fields; German-taught programs require a
  recognized language certificate.
- Application deadlines are earlier than many students expect — starting
  the process 8–10 months ahead of intake is standard advice.

## The trade-off

Austria's academic system rewards independent study, and English-taught
program options are narrower than in Germany or the Netherlands — strong
if your target field has one, worth checking early if it doesn't.

## After graduation

Non-EU graduates get a residence permit specifically to search for
qualifying work, giving genuine time to convert a degree into an Austrian
or wider-EU career.`;

const SOUTH_KOREA = `South Korea doesn't offer blanket free tuition the way Germany does — the
"free" pathway here runs through the **Korean Government Scholarship
Program (GKS)** and university-specific full-ride scholarships, both of
which are genuinely available to international students, including from
India, but are competitive rather than automatic.

## What "free" actually means here

GKS and equivalent university scholarships typically cover full tuition,
a monthly living stipend, and often flights and Korean language training
before the degree starts. Outside a scholarship, Korean public and private
university tuition is real and comparable to mid-range Western tuition —
so this pathway is specifically about qualifying for funding, not a
baseline low sticker price.

## What you'll still need to budget for

- **Application and standardized test costs** ahead of a scholarship
  application cycle.
- **Living costs** if your scholarship stipend doesn't fully cover Seoul
  or another major city's cost of living.
- **Korean language study**, if your target program is Korean-taught
  rather than English-taught.

## Eligibility basics

- Strong academic transcripts — GKS and top-university scholarships are
  genuinely competitive.
- TOPIK (Korean proficiency) for Korean-taught programs; IELTS/TOEFL for
  a growing number of English-taught programs, especially at the
  graduate level.
- Scholarship application cycles run on fixed annual windows — missing a
  deadline usually means waiting a full year.

## The trade-off

This is a merit-and-funding pathway, not a default low-cost one — it
suits strong applicants willing to build a competitive scholarship
application well ahead of time, not a fallback option decided last minute.

## After graduation

Korea offers a job-seeking visa pathway (D-10) for graduates, and a
growing number of multinational and Korean employers actively recruit
international graduates in tech, business, and engineering fields.`;

const USA_IVY = `The Ivy League and a number of other highly selective US universities
run **need-blind admissions with no-loan, full-need financial aid** —
meaning admitted students from lower- and middle-income families can
graduate with little to no tuition cost, funded entirely through grants
rather than loans. This isn't "free" the way Germany's public tuition is
— it's competitive and income-tested — but it is a real, verified pathway,
not a marketing simplification.

## What "free" actually means here

Several Ivy League schools cover full cost of attendance — tuition, room,
and board — for admitted students below a specific family income
threshold, and offer partial aid on a sliding scale above it. Because
these schools meet 100% of demonstrated financial need without loans, a
family's actual cost can end up dramatically lower than the published
sticker price.

## What you'll still need to budget for

- **Standardized testing and application costs** across multiple highly
  selective applications, since admission itself is the real bottleneck.
- **Travel and settling-in costs**, which aid packages don't always
  cover.
- **Non-covered personal expenses**, even under a full-need aid package.

## Eligibility basics

- Academically exceptional transcripts and standardized test scores
  (SAT/ACT where required, TOEFL/IELTS for English proficiency).
- A strong, distinctive application profile — these schools admit a small
  fraction of applicants, and financial aid doesn't change the admissions
  bar.
- Detailed family financial documentation for the need-based aid
  assessment (CSS Profile, in addition to the FAFSA where applicable).

## The trade-off

This pathway asks for a genuinely outstanding application, not just
financial need — it rewards strong students from any income bracket, but
admission is the hard part, not the funding.

## After graduation

An Ivy League or comparable US degree carries real weight with employers
and graduate programs worldwide, alongside standard US post-study work
options (OPT/STEM-OPT) for international graduates.`;

const JAPAN = `Japanese national universities charge a standardized, moderate tuition
fee rather than market-rate pricing — and the **MEXT Scholarship** (the
Japanese government's flagship scholarship) can bring that down to
genuinely free, alongside a monthly stipend, for successful applicants.

## What "free" actually means here

National university tuition is fixed by the government and identical
regardless of nationality — already lower than comparable Western tuition
even without a scholarship. MEXT and university-specific scholarships on
top of that can cover tuition in full, plus living costs, for students who
qualify.

## What you'll still need to budget for

- **Living costs**, particularly if based in Tokyo or another major city
  without a scholarship stipend.
- **Japanese language study**, for programs taught in Japanese rather
  than the still-limited number of English-taught programs.
- **Application costs**, including standardized test fees where required.

## Eligibility basics

- Strong academic transcripts, plus recommendation letters for
  scholarship applications.
- JLPT (Japanese proficiency) for Japanese-taught programs; IELTS/TOEFL
  increasingly accepted for English-taught programs, mostly at the
  graduate level.
- MEXT applications typically run through either the Japanese embassy or
  direct university recommendation — timelines are fixed and early.

## The trade-off

English-taught program options remain narrower than in Germany or the
Netherlands, and scholarship competition is real — this suits students
genuinely interested in Japan specifically, not a backup option.

## After graduation

Japan offers a post-study job-seeking visa extension, and a national push
to recruit international graduates into its workforce, particularly in
engineering and technology fields.`;

const NETHERLANDS = `The Netherlands is a partial-fit for "free" and worth being direct about:
**EU/EEA students** pay a low, government-set statutory fee, while
**non-EU students** (including Indian applicants) pay a higher
institutional fee set by each university — real tuition, not free. The
genuine low-cost/free angle for non-EU students runs through targeted
scholarships, most notably the **Holland Scholarship** and university-
specific awards, which can cover a significant part or all of first-year
tuition.

## What "low-cost" actually means here

Even at the non-EU institutional rate, Dutch tuition is frequently lower
than comparable UK, US, or Australian tuition for equivalent program
quality — and a wide, English-taught program catalogue (one of the
largest in continental Europe) means the “low tuition, high program
choice” trade-off is unusually favorable here even before any scholarship
is factored in.

## What you'll still need to budget for

- **Institutional tuition fee**, unless a scholarship specifically covers
  it — this is the key number to get an early, accurate quote on.
- **Proof of sufficient funds**, required for the residence permit.
- **Living costs**, which are moderate to high depending on city (Utrecht
  and Amsterdam run higher than smaller university towns).

## Eligibility basics

- Recognized academic transcripts; some programs require a numerus fixus
  (capped-entry) application process with its own deadline.
- English-taught programs are the norm at master's level and increasingly
  common at bachelor's level — IELTS/TOEFL is usually sufficient, Dutch
  is rarely required.
- Scholarship applications (Holland Scholarship, university-specific)
  typically run on separate, earlier deadlines than the general
  admissions cycle.

## The trade-off

This is genuinely lower-cost than several popular destinations, but it
isn't Germany-style free tuition for every applicant — getting an early,
accurate fee-plus-scholarship picture per university matters more here
than in most other countries on this list.

## After graduation

Graduates get a one-year "orientation year" residence permit to search
for qualifying work in the Netherlands — a meaningful runway to convert
the degree into a EU-based career.`;

const ITALY = `Italy's public universities — including the **University of Padua**, one
of the oldest and most respected in Europe — use an income-based fee
system (built around the ISEE, or equivalent international income
assessment) that applies to *all* students, domestic and international
alike. Students below a set family income threshold can pay little to no
tuition; the system isn't a special international discount, it's the same
mechanism every enrolled student goes through.

## What "free" actually means here

Public university tuition in Italy is generally lower than in the US, UK,
or Australia even at the top of the fee scale, and drops toward zero as
assessed family income falls below university-set thresholds — a genuine
need-based free-tuition mechanism, not a marketing simplification.

## What you'll still need to budget for

- **Income documentation (ISEE equivalent)**, needed early to get an
  accurate fee estimate — this is the single most important document to
  start on.
- **Proof of financial means**, required for the student visa
  independent of the tuition fee itself.
- **Living costs**, which vary significantly by city — Padua and similar
  university towns are notably more affordable than Rome or Milan.

## Eligibility basics

- Recognized academic transcripts, with a Declaration of Value (or
  equivalent) often required for foreign qualifications.
- English-taught programs are common at master's level at Padua and other
  major public universities; Italian-taught programs require an Italian
  proficiency certificate.
- The pre-enrollment process for international students typically runs
  through the Italian embassy/consulate — worth starting early.

## The trade-off

Getting the ISEE-equivalent income assessment right is the single biggest
factor in your actual cost — done early and correctly, it's what makes
this pathway genuinely affordable rather than merely "cheaper than
average."

## After graduation

Italy offers a post-study residence permit to search for qualifying work,
and University of Padua's international reputation carries real weight
for both further study and employment across the EU.`;

